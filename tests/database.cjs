const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { PGlite } = require('@electric-sql/pglite');
const { pgcrypto } = require('@electric-sql/pglite/contrib/pgcrypto');

(async()=>{
  const db = new PGlite({extensions:{pgcrypto}});
  let assertions = 0;
  const check = (condition,message) => { assert.ok(condition,message);assertions++; };
  const one = async (sql,args=[]) => (await db.query(sql,args)).rows[0];
  const expectError = async (fn,pattern) => { await assert.rejects(fn,pattern);assertions++; };
  const user = async (id,role='authenticated') => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);
    await db.exec('set role '+role);
  };
  const rpc = async (workspace,action,payload={}) => (await one('select public.transport_operator($1,$2,$3::jsonb) as result',[workspace,action,JSON.stringify(payload)])).result;
  const driver = async (token,action='get',payload={}) => (await one('select public.transport_driver($1,$2,$3::jsonb) as result',[token,action,JSON.stringify(payload)])).result;
  try {
    await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
      create schema auth;create schema extensions;create extension pgcrypto with schema extensions;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz default now());
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth,extensions to anon,authenticated;
      grant execute on function auth.uid() to anon,authenticated;`);
    const dir = path.join(__dirname,'../supabase/migrations');
    for (const file of fs.readdirSync(dir).filter(f=>f.endsWith('.sql')).sort())await db.exec(fs.readFileSync(path.join(dir,file),'utf8'));
    const {id:w} = await one("select id from public.to_workspaces where slug='delivery-ops-5l'");
    const admin=randomUUID(), outsider=randomUUID(), viewer=randomUUID();
    await db.query("insert into auth.users(id,email) values ($1,'owner@example.invalid'),($2,'outsider@example.invalid'),($3,'viewer@example.invalid')",[admin,outsider,viewer]);
    await db.query("insert into public.to_members(workspace_id,user_id,role) values($1,$2,'admin'),($1,$3,'viewer')",[w,admin,viewer]);
    const w2=(await one("insert into public.to_workspaces(slug,name) values('other-test','Other') returning id")).id;
    await db.query("insert into public.to_members(workspace_id,user_id,role) values($1,$2,'admin')",[w2,outsider]);
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/bootstrap_operator.sql'),'utf8').replace('REPLACE_WITH_YOUR_EMAIL','owner@example.invalid'));
    check(Number((await one("select count(*) as n from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','transport_private') and c.relkind='r' and c.relname like any(array['to_%','driver_links']) and not c.relrowsecurity")).n)===0,'Every app table has RLS');
    check(Number((await one('select count(*) as n from public.to_destinations')).n)>0,'Destination presets seeded');
    await user(null,'anon');
    await expectError(()=>db.query('select * from public.to_pallets'),/permission denied/);
    await expectError(()=>db.query('select * from transport_private.driver_links'),/permission denied/);
    await expectError(()=>rpc(w,'create_manifest',{building:'Building 21'}),/permission denied/);
    await expectError(()=>driver('0'.repeat(64)),/Invalid or expired/);
    await user(outsider);
    check(Number((await one('select count(*) as n from public.to_workspaces where id=$1',[w])).n)===0,'Other workspace invisible');
    await expectError(()=>rpc(w,'create_manifest',{building:'Building 21'}),/operator access/);
    await user(viewer);
    check(Number((await one('select count(*) as n from public.to_workspaces where id=$1',[w])).n)===1,'Viewer can read own workspace');
    await expectError(()=>rpc(w,'create_manifest',{building:'Building 21'}),/operator access/);
    await user(admin);
    await expectError(()=>db.query("insert into public.to_events(workspace_id,action,reference_id,actor_kind) values($1,'forged','x','operator')",[w]),/permission denied/);
    const origin={building:'Building 05',department:'Delivery Ops',shipTo:'B5L'};
    const destination={building:'Building 21',department:'Motion',shipTo:'B21-MOASSY'};
    const make=(p,f,hu,dest=destination)=>({expectedRowVersion:0,pallet:{id:p,status:'finalised',revision:1,destination:dest},forms:[{id:f,status:'complete',revision:1,origin,destination:dest,remarks:'OPERATOR PRIVATE NOTE',lines:[{hu,dn:'00001234',qty:'2.5',part:'',description:''}]}]});
    await rpc(w,'save_pallet',make('P-TEST1','TO-TEST1','000001'));
    await rpc(w,'save_pallet',make('P-TEST2','TO-TEST2','000002'));
    const otherDest={building:'Building 17',department:'Motion',shipTo:'B17-MOTION'};
    await rpc(w,'save_pallet',make('P-OTHER','TO-OTHER','000003',otherDest));
    await expectError(()=>rpc(w,'save_pallet',make('P-DUP','TO-DUP','000001')),/unique/);
    check(Number((await one("select count(*) as n from public.to_pallets where id='P-DUP'")).n)===0,'Failed save is atomic');
    await expectError(()=>rpc(w,'save_pallet',make('P-TEST1','TO-TEST1','000001')),/changed/);
    const bad=make('P-BAD','TO-BAD','000099');bad.forms[0].lines[0].qty='NaN';
    await expectError(()=>rpc(w,'save_pallet',bad),/check constraint/);
    const mixed=make('P-MIXED','TO-MIXED','000098');mixed.forms[0].lines=[{hu:'M1',qty:'1',sourceShipTo:'X'},{hu:'M2',qty:'1',sourceShipTo:'Y'}];
    await expectError(()=>rpc(w,'save_pallet',mixed),/Mixed SAP/);
    const created=await rpc(w,'create_manifest',{building:' building  21 '});
    check(created.palletCount===2,'Manifest includes all ready pallets for normalised building');
    await rpc(w,'save_pallet',make('P-LATER','TO-LATER','000004'));
    const separate=await rpc(w,'create_manifest',{building:'Building 21'});
    check(separate.palletCount===1,'Later pallet stays on a separate manifest');
    const token=created.driverToken;
    check(token.length===64,'256-bit driver capability');
    await expectError(()=>rpc(w,'create_manifest',{building:'Building 21'}),/No unassigned/);
    await expectError(()=>rpc(w,'reopen_pallet',{id:'P-TEST1',expectedRowVersion:1,reason:'Fix'}),/unreserved/);
    await user(null,'anon');
    const dto=await driver(token);
    check(dto.pallets.length===2&&dto.scannedCount===0,'Scoped driver load visible');
    check(!JSON.stringify(dto).includes('OPERATOR PRIVATE NOTE'),'Driver DTO excludes operator notes');
    await expectError(()=>driver(token,'scan',{code:'TO:PALLET:P-OTHER:1'}),/Wrong destination/);
    await expectError(()=>driver(token,'scan',{code:'TO:PALLET:P-TEST1:9'}),/Superseded/);
    await expectError(()=>driver(token,'scan',{code:'TO:PALLET:P-LATER:1'}),/not on this manifest/);
    await expectError(()=>db.query('select transport_private.issue_link($1,$2)',[w,created.id]),/permission denied/);
    const scan=await driver(token,'scan',{code:'TO:PALLET:P-TEST1:1'});
    check(scan.scannedCount===1,'Valid scan increments progress');
    const duplicate=await driver(token,'scan',{code:'TO:PALLET:P-TEST1:1'});
    check(duplicate.duplicate&&duplicate.scannedCount===1,'Duplicate scan is idempotent');
    await driver(token,'unscan',{palletId:'P-TEST1',reason:'Unload for rearrangement'});
    check((await driver(token)).scannedCount===0,'Unload reverses scan');
    await driver(token,'scan',{code:'TO:PALLET:P-TEST1:1'});
    await expectError(()=>driver(token,'confirm_pickup',{driver:'Driver',vehicle:'TEST-01'}),/partial pickup/);
    const partial=await driver(token,'confirm_pickup',{driver:'Driver',vehicle:'TEST-01',reason:'Truck full'});
    check(partial.status==='partial','Partial pickup confirmed');
    await expectError(()=>driver(token,'scan',{code:'TO:PALLET:P-TEST2:1'}),/already closed/);
    await expectError(()=>driver(token,'confirm_delivery',{building:'Building 17',receiver:'Receiver'}),/matching destination/);
    check((await driver(token,'confirm_delivery',{building:'Building 21',receiver:'Receiver'})).status==='delivered','Matching delivery confirmed');
    await user(admin);
    const remaining=await rpc(w,'create_manifest',{building:'Building 21'});
    check(remaining.palletCount===1,'Only uncollected pallet enters next manifest');
    const renewed=await rpc(w,'rotate_driver_link',{id:remaining.id,expectedRowVersion:1});
    await user(null,'anon');
    await expectError(()=>driver(remaining.driverToken),/Invalid or expired/);
    check((await driver(renewed.driverToken)).pallets.length===1,'New scoped token works');
    await user(admin);
    await rpc(w,'cancel_manifest',{id:remaining.id,expectedRowVersion:2,reason:'Truck cancelled'});
    await user(null,'anon');
    await expectError(()=>driver(renewed.driverToken),/Invalid or expired/);
    await user(admin);
    await rpc(w,'reopen_pallet',{id:'P-TEST2',expectedRowVersion:1,reason:'Correct pallet'});
    const immutable=make('P-TEST2','TO-TEST2','000002');immutable.expectedRowVersion=2;immutable.pallet.revision=2;immutable.forms[0].lines[0].qty='99';
    await expectError(()=>rpc(w,'save_pallet',immutable),/immutable/);
    const changed=make('P-TEST2','TO-TEST2','000002');changed.expectedRowVersion=2;changed.pallet.revision=2;changed.forms[0].revision=2;
    await rpc(w,'save_pallet',changed);
    const latest=await rpc(w,'create_manifest',{building:'Building 21'});
    await user(null,'anon');
    await expectError(()=>driver(latest.driverToken,'scan',{code:'TO:PALLET:P-TEST2:1'}),/Superseded/);
    await driver(latest.driverToken,'scan',{code:'TO:PALLET:P-TEST2:2'});
    check((await driver(latest.driverToken,'confirm_pickup',{driver:'Driver 2',vehicle:'TEST-02'})).status==='collected','Full pickup confirmed');
    await user(admin);
    await expectError(()=>rpc(w,'reopen_pallet',{id:'P-TEST1',expectedRowVersion:3,reason:'Fix'}),/uncollected/);
    await rpc(w,'set_dock_slots',{slots:[{building:'Building 21',days:[0,1,2,3,4],start:'09:00',end:'09:30'}]});
    await expectError(()=>rpc(w,'set_dock_slots',{slots:[{building:'Building 21',days:[6],start:'09:00',end:'09:30'}]}),/check constraint/);
    check(Number((await one('select count(*) as n from public.to_dock_slots')).n)===1,'Invalid slots do not delete valid schedule');
    check(Number((await one('select count(*) as n from public.to_documents')).n)>=9,'Historical documents retained');
    check(Number((await one('select count(*) as n from public.to_events')).n)>10,'Audit trail retained');
    await db.exec('reset role');
    await db.query("update transport_private.driver_links set expires_at=now()-interval '1 second' where manifest_id=$1",[separate.id]);
    await user(null,'anon');
    await expectError(()=>driver(separate.driverToken),/Invalid or expired/);
    console.log(`Database checks passed: ${assertions} assertions using PostgreSQL/PGlite with pgcrypto, role isolation, real RPCs, loading, revisions and delivery.`);
  } finally { await db.close(); }
})().catch(error=>{ console.error(error.message,error.where||'');process.exitCode=1; });
